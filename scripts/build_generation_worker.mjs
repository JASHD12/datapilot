/** Deterministic single-module Pages worker; no extra bundling dependency. */
import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {resolve} from 'node:path';
const root=new URL('..',import.meta.url);
const read=path=>readFile(new URL(path,root),'utf8');
const semantic=await read('frontend/semantic-search.js');
// Only the pure retrieval helpers; browser inference code is never shipped server-side.
const end=semantic.indexOf('export class ');
if(end<0)throw new Error('Semantic module structure changed.');
const helpers=semantic.slice(0,end).replace(/^export /gm,'');
const core=(await read('frontend/generation-core.js')).replace(/^import .*;\n/m,'').replace(/^export /gm,'');
const worker=(await read('cloudflare/generation-worker.js')).replace(/^import[\s\S]*?from '\.\.\/frontend\/generation-core.js';\n/m,'').replace(/^export /gm,'');
const artifact=JSON.parse(await read('frontend/retrieval-study.json'));
const corpus={passages:artifact.passages,lexical_index:artifact.lexical_index,methods:artifact.methods.filter(m=>m.id==='lexical'),cases:artifact.cases.filter(c=>c.split==='dev')};
const bundle=`// Generated by scripts/build_generation_worker.mjs.\nconst {lexicalScores,rank,selectThreshold}=(()=>{\n${helpers}\nreturn {lexicalScores,rank,selectThreshold};})();\n${core}\n${worker}\nconst CORPUS=${JSON.stringify(corpus)};\nexport default {fetch(request,env){return handleGeneration(request,env,CORPUS);}};\n`;
const directory=resolve(process.argv[2]||'artifacts/generation-preview');
await mkdir(directory,{recursive:true});
await writeFile(resolve(directory,'_worker.js'),bundle);
await writeFile(resolve(directory,'_routes.json'),JSON.stringify({version:1,include:['/api/generate','/api/generation-health'],exclude:[]}));
console.log(JSON.stringify({worker:resolve(directory,'_worker.js'),bytes:Buffer.byteLength(bundle),passages:corpus.passages.length}));
