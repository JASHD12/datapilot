"""Validated local data ingestion and an explicitly synthetic demonstration dataset.

The demo is a teaching fixture, not observations from a company. At order time,
``delivery_days``, ``delivery_late`` and ``review_rating`` are unknown outcomes.
They must never be used as inputs to an order-time delivery prediction.
"""

from __future__ import annotations

from io import BytesIO
from typing import Any

import numpy as np
import pandas as pd

MAX_CSV_BYTES = 20 * 1024 * 1024
MAX_ROWS = 100_000
MAX_COLUMNS = 100


def _value(value: Any) -> Any:
    """Convert pandas/numpy scalars to strict JSON primitives."""
    if value is None or (not isinstance(value, (list, dict)) and pd.isna(value)):
        return None
    if isinstance(value, (pd.Timestamp, np.datetime64)):
        return pd.Timestamp(value).isoformat()
    if isinstance(value, (np.integer,)):
        return int(value)
    if isinstance(value, (np.floating, float)):
        return float(value) if np.isfinite(value) else None
    if isinstance(value, np.bool_):
        return bool(value)
    return value


def records(frame: pd.DataFrame) -> list[dict[str, Any]]:
    return [{str(k): _value(v) for k, v in row.items()} for row in frame.to_dict("records")]


def demo_frame(seed: int = 42, rows: int = 1400) -> pd.DataFrame:
    """Generate reproducible synthetic orders with learnable, imperfect outcomes.

    Values and relationships are invented. Seller and product categories, weather
    seasonality, and shipping noise are simulated rather than measured. Outcomes
    are generated together for the fixture; callers still enforce order-time
    feature availability when training models.
    """
    if isinstance(rows, bool) or not isinstance(rows, int) or not 1 <= rows <= MAX_ROWS:
        raise ValueError(f"rows must be an integer between 1 and {MAX_ROWS:,}.")
    rng = np.random.default_rng(seed)
    dates = pd.date_range("2024-01-01", "2025-12-31", freq="D")
    day_number = np.arange(len(dates))
    weights = (1.0 + 0.35 * (dates.day_of_week < 5) + 0.5 * (dates.month >= 11))
    weights = np.asarray(weights) * (0.8 + 0.4 * day_number / len(dates))
    purchase_date = pd.DatetimeIndex(rng.choice(dates.values, size=rows, p=weights / weights.sum()))
    category = rng.choice(["electronics", "home", "fashion", "sports", "books"], rows,
                          p=[0.23, 0.28, 0.22, 0.13, 0.14])
    category_value = pd.Series(category).map({"electronics": 1.6, "home": 1.1,
                                             "fashion": 0.8, "sports": 1.0, "books": 0.4}).to_numpy()
    distance = np.clip(rng.gamma(2.0, 210.0, rows), 8, 1900)
    items = rng.choice([1, 2, 3, 4, 5], rows, p=[0.62, 0.23, 0.09, 0.04, 0.02])
    order_value = np.round(rng.lognormal(3.9, 0.55, rows) * category_value * items, 2)
    freight_value = np.round(3.0 + distance * 0.012 + items * 0.8 + rng.uniform(0.0, 4.0, rows), 2)
    promised_days = rng.integers(3, 10, rows)
    seller_index = rng.integers(0, 24, rows)
    seller_effect = (seller_index % 5 - 2) * 0.28
    winter = np.asarray(purchase_date.month.isin([11, 12, 1]), dtype=float)
    delivery_days = np.maximum(1, np.rint(2.5 + distance / 180 + winter * 0.9
                                         + (category == "home") * 0.7 + seller_effect
                                         + rng.normal(0, 1.45, rows))).astype(int)
    late = (delivery_days > promised_days).astype(int)
    review = np.clip(np.rint(4.5 - late * 1.6 + rng.normal(0, 0.7, rows)), 1, 5).astype(int)
    frame = pd.DataFrame({
        "order_id": [f"DEMO-{i + 1:06d}" for i in range(rows)],
        "purchase_date": purchase_date,
        "order_value": order_value,
        "freight_value": freight_value,
        "distance_km": np.round(distance, 1),
        "promised_days": promised_days,
        "items_count": items,
        "category": category,
        "seller_id": [f"seller_{i:02d}" for i in seller_index],
        "delivery_days": delivery_days,
        "delivery_late": late,
        "review_rating": review,
        "outcome_available_date": purchase_date + pd.to_timedelta(delivery_days, unit="D"),
    }).sort_values(["purchase_date", "order_id"]).reset_index(drop=True)
    # A small amount of missing order-time data exercises imputation honestly.
    if rows >= 50:
        frame.loc[rng.choice(rows, max(1, rows // 70), replace=False), "distance_km"] = np.nan
        frame.loc[rng.choice(rows, max(1, rows // 100), replace=False), "category"] = None
    frame.attrs["source"] = "Synthetic demonstration generated by DataPilot; not real company data."
    frame.attrs["seed"] = seed
    return frame


def load_csv_bytes(content: bytes) -> pd.DataFrame:
    """Load a bounded UTF-8 CSV without evaluating its contents."""
    if not isinstance(content, bytes) or not content.strip():
        raise ValueError("Upload a non-empty CSV file.")
    if len(content) > MAX_CSV_BYTES:
        raise ValueError("CSV file exceeds the 20 MiB upload limit.")
    if b"\x00" in content:
        raise ValueError("The file contains binary data. Upload a UTF-8 CSV.")
    try:
        header = content.decode("utf-8-sig").splitlines()[0]
        # Pandas silently renames duplicate headers; reject them explicitly.
        import csv
        column_names = next(csv.reader([header]))
        if any(not name.strip() for name in column_names):
            raise ValueError("CSV column names must not be blank.")
        normalized = [name.strip() for name in column_names]
        if len(set(normalized)) != len(normalized):
            raise ValueError("CSV column names must be unique.")
        if len(column_names) > MAX_COLUMNS:
            raise ValueError(f"CSV files may contain at most {MAX_COLUMNS} columns.")
        frame = pd.read_csv(BytesIO(content), nrows=MAX_ROWS + 1, encoding="utf-8-sig")
    except (UnicodeDecodeError, pd.errors.ParserError, pd.errors.EmptyDataError, csv.Error) as exc:
        raise ValueError("Unable to parse the file. Use a comma-separated UTF-8 CSV with a header.") from exc
    frame.columns = [str(name).strip() for name in frame.columns]
    if frame.empty:
        raise ValueError("The CSV has a header but no data rows.")
    if len(frame) > MAX_ROWS:
        raise ValueError(f"CSV files may contain at most {MAX_ROWS:,} rows.")
    for column in frame.columns:
        if column.lower().endswith(("_date", "_timestamp")):
            parsed = pd.to_datetime(frame[column], errors="coerce", utc=True)
            if parsed.notna().sum() == frame[column].notna().sum():
                frame[column] = parsed.dt.tz_convert(None)
    frame.attrs["source"] = "User-uploaded CSV; provenance and permitted use are supplied by the uploader."
    return frame


def profile_frame(df: pd.DataFrame) -> dict[str, Any]:
    """Return bounded, strict-JSON profile data suitable for API/UI rendering."""
    if not isinstance(df, pd.DataFrame) or df.empty:
        raise ValueError("The dataset must contain at least one row.")
    if not df.columns.is_unique:
        raise ValueError("Dataset column names must be unique.")
    numeric = list(df.select_dtypes(include="number").columns)
    categorical = [c for c in df.columns if c not in numeric and not pd.api.types.is_datetime64_any_dtype(df[c])]
    summaries: dict[str, Any] = {}
    for column in numeric:
        values = pd.to_numeric(df[column], errors="coerce").replace([np.inf, -np.inf], np.nan).dropna()
        summaries[str(column)] = {
            "min": _value(values.min()) if len(values) else None,
            "max": _value(values.max()) if len(values) else None,
            "mean": _value(values.mean()) if len(values) else None,
            "median": _value(values.median()) if len(values) else None,
            "std": _value(values.std()) if len(values) > 1 else None,
        }
    daily: list[dict[str, Any]] = []
    date_column = "purchase_date" if "purchase_date" in df else next(
        (c for c in df if pd.api.types.is_datetime64_any_dtype(df[c])), None)
    if date_column is not None:
        dates = pd.to_datetime(df[date_column], errors="coerce", utc=True).dropna().dt.floor("D")
        counts = dates.value_counts().sort_index().tail(1095)
        daily = [{"date": date.strftime("%Y-%m-%d"), "count": int(count)} for date, count in counts.items()]
    category_column = "category" if "category" in df else (categorical[0] if categorical else None)
    categories = []
    if category_column is not None:
        counts = df[category_column].fillna("(missing)").astype(str).value_counts().head(12)
        categories = [{"category": str(label), "count": int(count)} for label, count in counts.items()]
    order_values: list[dict[str, Any]] = []
    value_column = "order_value" if "order_value" in df else (numeric[0] if numeric else None)
    if value_column is not None:
        values = pd.to_numeric(df[value_column], errors="coerce").replace([np.inf, -np.inf], np.nan).dropna()
        if len(values):
            counts, edges = np.histogram(values, bins=min(15, max(1, len(values.unique()))))
            order_values = [{"start": float(edges[i]), "end": float(edges[i + 1]), "count": int(count)}
                            for i, count in enumerate(counts)]
    return {
        "rows": int(len(df)), "column_count": int(len(df.columns)),
        "missing_cells": int(df.isna().sum().sum()), "duplicate_rows": int(df.duplicated().sum()),
        "numerical": [str(c) for c in numeric], "categorical": [str(c) for c in categorical],
        "columns": [{"name": str(c), "dtype": str(df[c].dtype), "missing": int(df[c].isna().sum()),
                     "unique": int(df[c].nunique())} for c in df.columns],
        "summary": summaries, "preview": records(df.head(12)),
        "charts": {"daily_orders": daily, "categories": categories, "order_values": order_values},
        "source": df.attrs.get("source", "Dataset provenance has not been verified."),
    }
